-- 6) Keep the id counters ahead of the numbers the app chooses, so a record
--    added from the SQL editor or the REST API (without an id) gets the next free number
create or replace function public.keep_id_sequence() returns trigger
language plpgsql security definer set search_path = public as $$
declare seq text := pg_get_serial_sequence(format('%I.%I', tg_table_schema, tg_table_name), tg_argv[0]);
begin
  if seq is not null then
    execute format('select setval(%L, greatest((select coalesce(max(%I), 0) from %I.%I), 1))', seq, tg_argv[0], tg_table_schema, tg_table_name);
  end if;
  return null;
end; $$;
do $$
declare t record;
begin
  for t in select * from (values
    ('role','role_id'), ('permission','permission_id'), ('system_setting','setting_id'), ('report','report_id'),
    ('category','category_id'), ('product','product_id'), ('batch','batch_id'), ('stock_movement','movement_id'),
    ('stock_alert','alert_id'), ('returned_item','return_id'), ('customer','customer_id'), ('credit_account','account_id'),
    ('sales_order','order_id'), ('sales_order_item','item_id'), ('invoice','invoice_id'), ('discount','discount_id'),
    ('warranty_record','warranty_id'), ('exchange_request','request_id'), ('refund','refund_id'), ('complaint','complaint_id'),
    ('service_job','job_id'), ('service_visit_log','visit_log_id'), ('spare_part_request','request_id'), ('supplier','supplier_id'),
    ('quotation','quotation_id'), ('purchase_order','po_id'), ('purchase_order_item','item_id'), ('payable','payable_id'),
    ('payment','payment_id'), ('transaction','transaction_id'), ('technician','technician_id'), ('audit_log','audit_id')
  ) as v(tbl, pk) loop
    execute format('drop trigger if exists keep_id_sequence on %I', t.tbl);
    execute format('create trigger keep_id_sequence after insert on %I for each statement execute function public.keep_id_sequence(%L)', t.tbl, t.pk);
  end loop;
end $$;
