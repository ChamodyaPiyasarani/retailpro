-- 2) the 28 tables (same order as the Table Design)
-- System user (staff) accounts
create table "user" (
  user_id integer generated by default as identity primary key,
  name varchar(100) not null,
  email varchar(100) not null unique,
  password varchar(255),
  phone varchar(15),
  is_active boolean default true,
  created_date date,
  last_login timestamptz,
  role_id integer
);
-- User roles (Admin, Cashier, Storekeeper, Purchasing Manager, Finance Manager, Technician)
create table role (
  role_id integer generated by default as identity primary key,
  role_name varchar(50) not null unique,
  description varchar(200),
  is_active boolean default true
);
-- System functions that can be allowed to a role
create table permission (
  permission_id integer generated by default as identity primary key,
  permission_name varchar(100) not null unique,
  module varchar(50),
  description varchar(200)
);
-- Which permissions each role has (M:N relationship between Role and Permission)
create table role_permission (
  role_id integer not null,
  permission_id integer not null,
  granted_date date,
  primary key (role_id, permission_id)
);
-- Extra details of users who are technicians
create table technician (
  technician_id integer generated by default as identity primary key,
  is_available boolean default true,
  experience_years integer,
  user_id integer unique
);
-- Skills of each technician (multivalued attribute)
create table technician_specialisation (
  technician_id integer not null,
  specialisation varchar(50) not null,
  primary key (technician_id, specialisation)
);
-- Product categories
create table category (
  category_id integer generated by default as identity primary key,
  category_name varchar(50) not null,
  description varchar(200),
  is_active boolean default true
);
-- Computer hardware products and spare parts
create table product (
  product_id integer generated by default as identity primary key,
  product_name varchar(100) not null,
  brand varchar(50),
  model varchar(50),
  unit_price numeric(10,2),
  cost_price numeric(10,2),
  stock_qty integer,
  reorder_level integer,
  warranty_months integer,
  is_active boolean default true,
  category_id integer
);
-- Suppliers of products
create table supplier (
  supplier_id integer generated by default as identity primary key,
  supplier_name varchar(100) not null,
  contact_person varchar(100),
  phone varchar(15),
  email varchar(100) not null,
  address varchar(200),
  is_active boolean default true
);
-- Which supplier supplies which product (M:N relationship)
create table product_supplier (
  product_id integer not null,
  supplier_id integer not null,
  primary key (product_id, supplier_id)
);
-- Customers of the shop
create table customer (
  customer_id integer generated by default as identity primary key,
  name varchar(100) not null,
  phone varchar(15),
  email varchar(100) not null,
  address varchar(200),
  registered_date date
);
-- Discount codes
create table discount (
  discount_id integer generated by default as identity primary key,
  discount_code varchar(20) not null unique,
  rate numeric(10,2),
  description varchar(200),
  start_date date,
  end_date date,
  is_active boolean default true
);
-- Sales made at the counter
create table sales_order (
  order_id integer generated by default as identity primary key,
  order_date date not null,
  subtotal numeric(10,2),
  discount_amount numeric(10,2) default 0,
  total_amount numeric(10,2),
  status varchar(20) not null,
  customer_id integer,
  user_id integer,
  discount_id integer
);
-- Products in each sales order
create table sales_order_item (
  item_id integer generated by default as identity primary key,
  quantity integer not null,
  unit_price numeric(10,2),
  subtotal numeric(10,2),
  order_id integer,
  product_id integer
);
-- Invoice of a sales order or of a completed service job with a service charge
create table invoice (
  invoice_id integer generated by default as identity primary key,
  invoice_date date not null,
  amount numeric(10,2) not null,
  paid_amount numeric(10,2) default 0,
  due_date date,
  status varchar(20) not null,
  order_id integer,
  job_id integer
);
-- Warranty of each sold item
create table warranty (
  warranty_id integer generated by default as identity primary key,
  start_date date,
  end_date date,
  status varchar(20) not null,
  item_id integer
);
-- Customer requests to return a product for a refund
create table return_request (
  request_id integer generated by default as identity primary key,
  request_date date not null,
  reason varchar(200),
  status varchar(20) not null,
  approved_date date,
  order_id integer,
  product_id integer
);
-- Money paid back for approved returns
create table refund (
  refund_id integer generated by default as identity primary key,
  refund_date date not null,
  amount numeric(10,2) not null,
  method varchar(20),
  request_id integer
);
-- Price quotations from suppliers
create table quotation (
  quotation_id integer generated by default as identity primary key,
  request_date date not null,
  quantity integer not null,
  valid_until date,
  quoted_price numeric(10,2),
  status varchar(20) not null,
  supplier_id integer,
  product_id integer
);
-- Orders sent to suppliers
create table purchase_order (
  po_id integer generated by default as identity primary key,
  order_date date not null,
  expected_date date,
  total_amount numeric(10,2),
  status varchar(20) not null,
  supplier_id integer,
  user_id integer,
  quotation_id integer
);
-- Products in each purchase order
create table purchase_order_item (
  item_id integer generated by default as identity primary key,
  quantity integer not null,
  received_qty integer default 0,
  unit_cost numeric(10,2),
  po_id integer,
  product_id integer
);
-- Customer payments and supplier payments
create table payment (
  payment_id integer generated by default as identity primary key,
  payment_date date not null,
  amount numeric(10,2) not null,
  method varchar(20),
  payment_type varchar(20),
  receipt_no varchar(20),
  cheque_no varchar(20),
  user_id integer,
  invoice_id integer,
  po_id integer
);
-- Repair and service jobs
create table service_job (
  job_id integer generated by default as identity primary key,
  job_type varchar(20),
  fault varchar(200),
  status varchar(20) not null,
  request_date date not null,
  completed_date date,
  service_charge numeric(10,2) default 0,
  customer_id integer,
  product_id integer,
  technician_id integer
);
-- Repair details written by technicians
create table repair_note (
  note_id integer generated by default as identity primary key,
  note_date date not null,
  details varchar(300),
  job_id integer
);
-- Spare parts asked for a service job
create table spare_part_request (
  request_id integer generated by default as identity primary key,
  quantity integer not null,
  status varchar(20) not null,
  request_date date not null,
  job_id integer,
  product_id integer
);
-- Every stock in, stock out and adjustment
create table stock_movement (
  movement_id integer generated by default as identity primary key,
  movement_type varchar(20) not null,
  quantity integer not null,
  reason varchar(100),
  movement_date date not null,
  product_id integer,
  user_id integer,
  po_id integer,
  job_id integer
);
-- Low-stock alerts
create table stock_alert (
  alert_id integer generated by default as identity primary key,
  alert_date date not null,
  status varchar(20) not null,
  resolved_date date,
  product_id integer
);
-- Reports generated by users
create table report (
  report_id integer generated by default as identity primary key,
  report_type varchar(30) not null,
  from_date date,
  to_date date,
  created_date date,
  user_id integer
);

